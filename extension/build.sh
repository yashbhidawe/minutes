#!/usr/bin/env bash
#
# Build the distributable Minutes Chrome extension zip.
#
# Usage:
#   MINUTES_API_URL=https://137-23-40-60.nip.io \
#   MINUTES_SITE_URL=https://minutes.itsokyash.online \
#     ./extension/build.sh
#
# Output:
#   extension/minutes-extension.zip          (source of truth)
#   client/public/minutes-extension.zip      (served by Next.js / Vercel)
#   client/public/extension-version.json       (version metadata for /install)
#
# The script copies extension/ into a temp dir, rewrites config.js with the
# production URLs, then zips. Local dev files are never modified.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
EXT_DIR="$ROOT_DIR/extension"
CLIENT_PUBLIC="$ROOT_DIR/client/public"

API_URL="${MINUTES_API_URL:-https://137-23-40-60.nip.io}"
SITE_URL="${MINUTES_SITE_URL:-https://minutes.itsokyash.online}"
# Strip trailing slash so URL joins are predictable.
SITE_URL="${SITE_URL%/}"
API_URL="${API_URL%/}"

if [ -z "${MINUTES_API_URL:-}" ]; then
  echo "⚠️  MINUTES_API_URL not set — using placeholder $API_URL"
  echo "   Re-run with your real Render backend URL before announcing the download:"
  echo "   MINUTES_API_URL=https://<your-backend>.onrender.com ./extension/build.sh"
fi

VERSION="$(python3 -c "import json; print(json.load(open('$EXT_DIR/manifest.json'))['version'])")"
STAMP="$(date -u +%Y-%m-%dT%H:%M:%SZ)"

TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT
DIST="$TMP_DIR/minutes-extension"
mkdir -p "$DIST/icons"

# Copy packaged files (config.js is generated below with prod URLs).
cp "$EXT_DIR/manifest.json" "$EXT_DIR/background.js" "$EXT_DIR/content.js" \
   "$EXT_DIR/dashboard-sync.js" "$EXT_DIR/offscreen.html" "$EXT_DIR/offscreen.js" \
   "$EXT_DIR/permissions.html" "$EXT_DIR/permissions.js" \
   "$EXT_DIR/popup.html" "$EXT_DIR/popup.js" "$DIST/"
cp "$EXT_DIR/icons/"*.png "$DIST/icons/"

# Production config — dashboard hosts cover local dev + Vercel deploys.
cat > "$DIST/config.js" <<EOF
// Auto-generated by extension/build.sh — do not edit by hand.
// Built $STAMP | version $VERSION | api $API_URL | site $SITE_URL
const MINUTES_CONFIG = {
  API_BASE: "$API_URL",
  DASHBOARD_URL: "$SITE_URL",
  DASHBOARD_HOSTS: [
    "http://localhost:3000/*",
    "http://127.0.0.1:3000/*",
    "$SITE_URL/*",
    "https://*.vercel.app/*"
  ],
};
EOF

# Zip from inside the staging dir so manifest.json sits at the archive root
# (required for "Load unpacked" / zip installs).
python3 - "$DIST" "$EXT_DIR/minutes-extension.zip" <<'PYEOF'
import sys, zipfile
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zf:
    for path in sorted(src.rglob("*")):
        if path.is_file():
            zf.write(path, path.relative_to(src))
print(f"wrote {out} ({out.stat().st_size} bytes)")
PYEOF

mkdir -p "$CLIENT_PUBLIC"
cp "$EXT_DIR/minutes-extension.zip" "$CLIENT_PUBLIC/minutes-extension.zip"

python3 - "$CLIENT_PUBLIC/extension-version.json" "$VERSION" "$STAMP" <<'PYEOF'
import json, sys
out, version, stamp = sys.argv[1], sys.argv[2], sys.argv[3]
with open(out, "w") as f:
    json.dump(
        {
            "version": version,
            "downloadUrl": "/minutes-extension.zip",
            "updatedAt": stamp,
        },
        f,
        indent=2,
    )
    f.write("\n")
print(f"wrote {out} (v{version})")
PYEOF

echo "✅ Done. Download URL after deploy: $SITE_URL/minutes-extension.zip"
